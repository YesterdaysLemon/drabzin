const KEY = 'drabzin.lang';
let lang = 'en';

export const currentLang = () => lang;
export const langInfo = (id = lang) => LANGS.find((l) => l.id === id) || LANGS[0];

export function t(key, vars = {}) {
  const s = DICT[lang]?.[key] ?? DICT.en[key];
  if (s == null) return key;
  if (typeof s === 'function') return s(vars);
  return s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] != null ? String(vars[k]) : m));
}

// The language to start in: the one picked here before, else the browser's own if offered.
export function initialLang() {
  try { const saved = localStorage.getItem(KEY); if (saved && DICT[saved]) return saved; } catch { /* storage blocked */ }
  for (const l of navigator.languages || [navigator.language || 'en']) {
    const id = String(l).toLowerCase().split('-')[0];
    if (DICT[id]) return id;
  }
  return 'en';
}

export function setLang(id, { remember = true } = {}) {
  lang = DICT[id] ? id : 'en';
  const info = langInfo();
  document.documentElement.lang = info.id;
  document.documentElement.dir = info.dir;
  if (remember) { try { localStorage.setItem(KEY, lang); } catch { /* storage blocked */ } }
  applyI18n(document);
}

const ATTRS = ['title', 'aria-label', 'placeholder'];
export function applyI18n(root) {
  const vars = (el) => ({ ...el.dataset });
  for (const el of root.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n, vars(el));
  for (const el of root.querySelectorAll('[data-i18n-html]')) el.innerHTML = t(el.dataset.i18nHtml, vars(el));
  for (const a of ATTRS) {
    const prop = `i18n${a.split('-').map((p) => p[0].toUpperCase() + p.slice(1)).join('')}`;
    for (const el of root.querySelectorAll(`[data-i18n-${a}]`)) el.setAttribute(a, t(el.dataset[prop], vars(el)));
  }
}
